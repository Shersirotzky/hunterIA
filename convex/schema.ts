import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

const timestamps = {
  createdAt: v.number(),
  updatedAt: v.number(),
};

export default defineSchema({
  linkedinAccounts: defineTable({ subject: v.string(), userId: v.id("users") }).index("by_subject", ["subject"]),
  users: defineTable({
    role: v.union(v.literal("customer"), v.literal("admin"), v.literal("support")),
    createdAt: v.number(),
  }),
  platformAdmins: defineTable({
    subject: v.string(),
    role: v.union(v.literal("admin"), v.literal("support")),
    createdAt: v.number(),
  }).index("by_subject", ["subject"]),
  professionalProfiles: defineTable({
    ownerUserId: v.string(),
    linkedinSubject: v.string(),
    fullName: v.optional(v.string()),
    email: v.optional(v.string()),
    phone: v.optional(v.string()),
    headline: v.optional(v.string()),
    summary: v.optional(v.string()),
    workHistoryJson: v.string(),
    educationJson: v.string(),
    skillsJson: v.string(),
    languagesJson: v.string(),
    targetRolesJson: v.string(),
    locationsJson: v.string(),
    workModesJson: v.string(),
    salaryJson: v.string(),
    workAuthorization: v.optional(v.string()),
    preferredIndustriesJson: v.string(),
    excludedIndustriesJson: v.string(),
    standardAnswersJson: v.string(),
    sourceStatus: v.union(v.literal("pending_review"), v.literal("approved")),
    ...timestamps,
  }).index("by_owner", ["ownerUserId"]),
  documents: defineTable({
    ownerUserId: v.string(),
    kind: v.union(v.literal("resume"), v.literal("cover_letter"), v.literal("linkedin_export")),
    fileName: v.string(),
    storageId: v.string(),
    sha256: v.string(),
    approvedAt: v.optional(v.number()),
    ...timestamps,
  }).index("by_owner_kind", ["ownerUserId", "kind"]),
  jobSources: defineTable({
    ownerUserId: v.string(),
    name: v.string(),
    kind: v.union(v.literal("api"), v.literal("feed"), v.literal("career_page"), v.literal("manual")),
    baseUrl: v.string(),
    enabled: v.boolean(),
    lastRunAt: v.optional(v.number()),
    lastError: v.optional(v.string()),
    ...timestamps,
  }).index("by_owner", ["ownerUserId"]),
  automationRuns: defineTable({
    ownerUserId: v.string(),
    kind: v.union(v.literal("scheduled_search"), v.literal("analysis"), v.literal("submission_reconciliation")),
    status: v.union(v.literal("queued"), v.literal("running"), v.literal("completed"), v.literal("failed")),
    scheduledFor: v.number(),
    startedAt: v.optional(v.number()),
    finishedAt: v.optional(v.number()),
    foundCount: v.number(),
    error: v.optional(v.string()),
    ...timestamps,
  }).index("by_owner_scheduled", ["ownerUserId", "scheduledFor"]),
  platformAuthorizations: defineTable({
    ownerUserId: v.string(),
    platform: v.string(),
    enabled: v.boolean(),
    autoSubmit: v.boolean(),
    dailyLimit: v.number(),
    paused: v.boolean(),
    approvedAt: v.optional(v.number()),
    ...timestamps,
  }).index("by_owner_platform", ["ownerUserId", "platform"]),
  externalConnections: defineTable({
    ownerAccountId: v.optional(v.string()),
    ownerUserId: v.string(),
    provider: v.string(),
    subject: v.string(),
    profileJson: v.string(),
    tokenSecretRef: v.optional(v.string()),
    verifiedAt: v.optional(v.number()),
    authorizationExpiresAt: v.optional(v.number()),
    grantedScopes: v.optional(v.array(v.string())),
    ...timestamps,
  }).index("by_owner_provider", ["ownerUserId", "provider"]).index("by_provider_subject", ["provider","subject"]),
  linkedInAttempts: defineTable({
    ownerUserId: v.string(),
    stateHash: v.string(),
    expiresAt: v.number(),
    consumed: v.boolean(),
  }).index("by_owner", ["ownerUserId"]),
  ownerSettings: defineTable({
    ownerUserId: v.string(),
    timezone: v.string(),
    minimumMatchScore: v.number(),
    dailyApplicationLimit: v.number(),
    automationsPaused: v.boolean(),
    emailMonitoringEnabled: v.boolean(),
    pushNotificationsEnabled: v.boolean(),
    ...timestamps,
  }).index("by_owner", ["ownerUserId"]),
  jobs: defineTable({
    ownerUserId: v.string(),
    source: v.string(),
    sourceId: v.string(),
    canonicalUrl: v.string(),
    company: v.string(),
    title: v.string(),
    status: v.union(v.literal("open"), v.literal("closed"), v.literal("unknown")),
    collectedAt: v.number(),
    skills: v.optional(v.array(v.string())),
    description: v.optional(v.string()),
    ...timestamps,
  }).index("by_owner_source_id", ["ownerUserId", "source", "sourceId"]),
  jobMatches: defineTable({
    ownerUserId: v.string(),
    jobId: v.id("jobs"),
    score: v.number(),
    confidence: v.number(),
    recommendation: v.union(v.literal("apply"), v.literal("review"), v.literal("skip")),
    ...timestamps,
  }).index("by_owner_job", ["ownerUserId", "jobId"]),
  applications: defineTable({
    ownerUserId: v.string(),
    jobId: v.id("jobs"),
    status: v.union(
      v.literal("discovered"), v.literal("analyzed"), v.literal("eligible"),
      v.literal("preparing"), v.literal("ready"), v.literal("submitting"),
      v.literal("submitted"), v.literal("confirmed"), v.literal("needs_review"),
      v.literal("blocked"), v.literal("failed"), v.literal("unknown_result"),
      v.literal("cancelled"),
    ),
    draft: v.optional(v.object({ name: v.string(), email: v.string(), phone: v.string(), summary: v.string(), skills: v.array(v.string()), locations: v.optional(v.array(v.string())), roles: v.optional(v.array(v.string())), modes: v.optional(v.array(v.string())) })),
    submittedAt: v.optional(v.number()),
    dailyBucket: v.optional(v.string()),
    reservedAt: v.optional(v.number()),
    platform: v.optional(v.string()),
    confirmationEvidence: v.optional(v.string()),
    ...timestamps,
  }).index("by_owner_job", ["ownerUserId", "jobId"]).index("by_owner", ["ownerUserId"]),
  auditLogs: defineTable({
    ownerUserId: v.string(),
    action: v.string(),
    entityType: v.string(),
    entityId: v.optional(v.string()),
    result: v.union(v.literal("success"), v.literal("blocked"), v.literal("failure")),
    metadata: v.optional(v.string()),
    ...timestamps,
  }).index("by_owner_created", ["ownerUserId", "createdAt"]),
});
